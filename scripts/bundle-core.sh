#!/usr/bin/env bash
# Builds static/core.js, the one script every page built on base.html loads:
# scripts/core-src/modal.js + static/speech.js + scripts/core-src/say.js.
# (speech.js stays in static/ because the Sprint play page, which does not
# extend base.html, loads it alone.) core.js is checked in: after editing a
# source, run this and commit both.
# Usage: scripts/bundle-core.sh [--check]   (--check fails when core.js is stale)
set -euo pipefail
cd "$(dirname "$0")/.."
out=$(mktemp)
trap 'rm -f "$out"' EXIT
echo "// GENERATED by scripts/bundle-core.sh from scripts/core-src/modal.js, static/speech.js and scripts/core-src/say.js. Edit those, not this file." > "$out"
for f in scripts/core-src/modal.js static/speech.js scripts/core-src/say.js; do
  printf '\n// ---- %s ----\n' "$f" >> "$out"
  cat "$f" >> "$out"
  [ -z "$(tail -c1 "$f")" ] || echo >> "$out"
done
if [ "${1:-}" = "--check" ]; then
  cmp -s "$out" static/core.js || { echo "static/core.js is stale: run scripts/bundle-core.sh" >&2; exit 1; }
else
  cp "$out" static/core.js
fi
